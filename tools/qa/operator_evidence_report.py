#!/usr/bin/env python3
"""Offline, deliberately non-qualifying Bridge evidence summary for operators.

No access to application source or network needed; inputs are reports generated by
independent test tools. Never publish paths, raw exception text, secrets or PII.
Passing a Native Host runner or seeing inventory is NOT Windows/installer UAT.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

BLACKBOX_SCHEMA = 'sokna-bridge-binary-blackbox-v1'
INVENTORY_SCHEMA = 'sokna-bridge-windows-inventory-v1'
MATRIX_SCHEMA = 'sokna-bridge-independent-operator-qa-v1'


def _load(path):
    data = path.read_bytes()
    if len(data) > 16 * 1024 * 1024:
        raise ValueError('evidence input too large')
    obj = json.loads(data)
    if not isinstance(obj, dict):
        raise ValueError('evidence object required')
    return obj, hashlib.sha256(data).hexdigest()


def _fail(message):
    raise ValueError(message)


def blackbox(path):
    p, sha = _load(path)
    if p.get('schema') != BLACKBOX_SCHEMA or p.get('qualification') != 'isolated_native_host_only_not_windows_installer_uat':
        _fail('blackbox schema or qualification invalid')
    passes = p.get('passed')
    failures = p.get('failures')
    if failures is None:
        failures = []  # Go encodes a nil slice as JSON null on successful runs.
    if not isinstance(passes, list) or not isinstance(failures, list):
        _fail('blackbox results must be arrays or nullable failures')
    if not all(isinstance(x, str) for x in passes + failures):
        _fail('blackbox result item invalid')
    pc, fc = p.get('passed_count'), p.get('failed_count')
    if type(pc) is not int or type(fc) is not int or pc < 0 or fc < 0 or pc != len(passes) or fc != len(failures):
        _fail('blackbox result counters inconsistent')
    if len(set(passes)) != pc:
        _fail('blackbox duplicate test names')
    if pc + fc < 19:
        _fail('blackbox incomplete test suite')
    return {'status':'PASS' if fc == 0 else 'FAIL', 'passed_count':pc,
            'failed_count':fc,'evidence_sha256':sha,
            'qualification':'ISOLATED_NATIVE_HOST_ONLY'}


def inventory(path):
    p, sha = _load(path)
    if p.get('schema') != INVENTORY_SCHEMA or p.get('evidence_kind') != 'read_only_metadata_snapshot':
        _fail('windows inventory schema invalid')
    if p.get('real_uat_qualified') is not False:
        _fail('windows inventory cannot qualify UAT')
    for field in ('services', 'installed_entries', 'executable_hashes'):
        if p.get(field) is not None and not isinstance(p[field], list):
            _fail('inventory list invalid')
    return {'status':'INVENTORY_ONLY','evidence_sha256':sha,
            'services_count':len(p.get('services') or []),
            'installed_entries_count':len(p.get('installed_entries') or []),
            'binary_hashes_count':len(p.get('executable_hashes') or [])}


def matrix(path):
    p, sha = _load(path)
    if p.get('schema') != MATRIX_SCHEMA or not isinstance(p.get('cases'), list):
        _fail('scenario matrix schema invalid')
    cases=p['cases']
    ids=[]
    for c in cases:
        if not isinstance(c,dict) or not isinstance(c.get('id'),str) or not c['id']:
            _fail('scenario entry invalid')
        if c.get('status') not in ('NOT_RUN','PASS','FAIL','BLOCKED'):
            _fail('scenario status invalid')
        # This report is not allowed to accept unverified, manually asserted PASS.
        if c.get('status') != 'NOT_RUN':
            _fail('unverified scenario status not allowed in planning matrix')
        ids.append(c['id'])
    if len(ids) != len(set(ids)) or not cases:
        _fail('duplicate or empty matrix')
    return {'planned_count':len(cases),'not_run_count':len(cases),'evidence_sha256':sha}


def summarize(matrix_path, blackbox_path=None, inventory_path=None):
    plan=matrix(matrix_path)
    gates={'source_and_security_tests':'NOT_ATTESTED_BY_THIS_REPORT',
           'native_host_binary':'NOT_RUN',
           'windows_inventory':'NOT_RUN',
           'windows_installer_install_upgrade_rollback':'NOT_RUN',
           'chrome_edge_actual_extension_uat':'NOT_RUN',
           'target_application_end_to_end_uat':'NOT_RUN'}
    evidence={}
    if blackbox_path is not None:
        b=blackbox(blackbox_path)
        evidence['native_host_blackbox']=b
        gates['native_host_binary']=b['status']
    if inventory_path is not None:
        i=inventory(inventory_path)
        evidence['windows_readonly_inventory']=i
        gates['windows_inventory']=i['status']
    # These gates cannot be marked PASS through generic reports.
    return {'schema':'sokna-bridge-operator-evidence-summary-v1',
            'scope':'INDEPENDENT_BRIDGE_NOT_TARGET_APPLICATION',
            'read_only_report':True,
            'planned_scenarios':plan,
            'gates':gates,
            'evidence':evidence,
            'ready_for_github_transfer':False,
            'qualified_for_windows_install':False,
            'limitations':['No evidence of running Windows installer/upgrade/repair/rollback',
                           'No physical Chrome/Edge extension UAT',
                           'No real target application end-to-end test',
                           'No installer qualification inferred from Native Host or inventory']}


def main():
    arg=argparse.ArgumentParser(description=__doc__)
    arg.add_argument('--matrix',required=True,type=Path)
    arg.add_argument('--blackbox',type=Path)
    arg.add_argument('--windows-inventory',type=Path)
    arg.add_argument('--output',required=True,type=Path)
    a=arg.parse_args()
    try:
        summary=summarize(a.matrix,a.blackbox,a.windows_inventory)
        a.output.parent.mkdir(parents=True,exist_ok=True)
        if a.output.exists():
            raise ValueError('output already exists: refuse to overwrite evidence')
        # Only high-level schema-controlled fields are serialized.
        a.output.write_text(json.dumps(summary,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        print('OPERATOR_EVIDENCE_WRITTEN status=NOT_QUALIFIED')
        return 0 if summary['gates']['native_host_binary'] != 'FAIL' else 1
    except (OSError,ValueError,TypeError,json.JSONDecodeError) as exc:
        # Do not echo raw content, file paths or possible sensitive exceptions.
        print('OPERATOR_EVIDENCE_REJECTED',file=sys.stderr)
        return 2


if __name__=='__main__':
    raise SystemExit(main())
